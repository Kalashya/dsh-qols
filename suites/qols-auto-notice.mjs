import { evaluate } from '../features/auto/heuristic.js'
import { isTaskStart, createRouter } from '../features/auto/router.js'
import { config } from '../features/auto/config.js'

const notice = (text) => ({ role: 'user', content: [{ type: 'text', text }], source: { kind: 'model-selection', form: 'notice' } })
const user = (text) => ({ role: 'user', content: [{ type: 'text', text }] })
const assistant = { role: 'assistant', content: [{ type: 'text', text: 'ok' }], source: { kind: 'model', provider: 'deepseek-account' } }
const toolResult = { role: 'tool', content: [{ type: 'text', text: 'result' }], source: { kind: 'tool', callId: 'c1' } }

const NOTICE = '[model changed: assistant turns above this point were generated by deepseek-account/deepseek-flash; the session continues with qols-auto/auto]'
const tools = Array.from({ length: 40 }, (_, i) => ({ name: `tool${i}` }))

let checks = 0
const ok = (condition, label) => { if (!condition) throw new Error(`FAILED: ${label}`); checks += 1 }

// 1. A trailing model-switch notice must not become the task text.
const withNotice = [user('проверка qol auto'), notice(NOTICE)]
ok(isTaskStart(withNotice) === true, 'notice after a fresh prompt is still a task start')
const noticeEval = evaluate({ messages: withNotice, tools }, config)
ok(!noticeEval.signals.includes('many-tools'), 'tool schema count must not score the task')
console.log('notice case score:', noticeEval.score, 'signals:', noticeEval.signals.join(','))

// 2. Real text is used, so a short question is priced as a short question.
const question = [user('как работает этот роут?')]
ok(isTaskStart(question) === true, 'plain prompt starts a task')
const questionEval = evaluate({ messages: question, tools }, config)
console.log('short question:', questionEval.score, questionEval.tier, questionEval.signals.join(','))
ok(questionEval.tier === 'eco', 'short question routes to eco')
ok(questionEval.signals.includes('short-question'), 'short-question signal present')

// 3. A complexity phrase outranks the short-question shortcut.
const hard = [user('почему падает воркер при нагрузке?')]
const hardEval = evaluate({ messages: hard, tools }, config)
console.log('hard question:', hardEval.score, hardEval.tier, hardEval.signals.join(','))
ok(hardEval.tier !== 'eco', 'complex question must not route to eco')

// 4. Continuation steps keep the route; assistant/tool tails are not task starts.
ok(isTaskStart([user('x'), assistant]) === false, 'assistant tail is not a task start')
ok(isTaskStart([user('x'), assistant, toolResult]) === false, 'tool tail is not a task start')

// 5. A stale decision must not be reused when a new prompt follows a notice.
const calls = []
const llm = { async resolveCallConfig({ provider, model, reasoningEffort }) { calls.push({ provider, model, reasoningEffort }); return { provider, model, reasoningEffort } } }
const entries = []
const router = createRouter({ llm, config, log: () => {}, classify: async () => null, journal: { record: (entry) => entries.push(entry), last: () => entries.at(-1) ?? null } })
await router.decide({ sessionId: 's1', messages: [user('привет')], reasoningEffort: 'auto', provider: 'qols-auto', model: 'auto' })
const second = await router.decide({ sessionId: 's1', messages: [user('привет'), assistant, notice(NOTICE), user('отрефактори архитектуру модуля авторизации')], reasoningEffort: 'auto', provider: 'qols-auto', model: 'auto' })
console.log('second task tier:', second.tier, 'source:', second.source, 'reused:', second.reused === true)
ok(second.reused !== true, 'a notice must not make the next prompt look like a continuation')
ok(second.tier === 'deep', 'new complex prompt re-decides to deep')
ok(entries.length === 2, 'each task is journalled once')

console.log(`REGRESSION TESTS PASSED (${checks} checks)`)
